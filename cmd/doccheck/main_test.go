func TestRunReportsMissingDocumentation(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "good.go", `// Package sample is documented.
package sample

// Good is documented.
type Good interface {
	// Run does work.
	Run()
}

// Exported is documented.
func Exported() {}
`)
	var stdout, stderr bytes.Buffer
	if code := run([]string{root}, &stdout, &stderr); code != 0 {
		t.Fatalf("run() = %d, stderr = %q", code, stderr.String())
	}
	if stdout.Len() != 0 {
		t.Fatalf("stdout = %q", stdout.String())
	}

	writeSource(t, root, "bad.go", `package sample

type Missing interface {
	Call()
}

func Undocumented() {}
`)
	stdout.Reset()
	stderr.Reset()
	if code := run([]string{root}, &stdout, &stderr); code != 1 {
		t.Fatalf("run() = %d, want 1", code)
	}
	for _, expected := range []string{
		"Missing: missing doc comment",
		"Missing.Call: missing doc comment",
		"Undocumented: missing doc comment",
	} {
		if !strings.Contains(stdout.String(), expected) {
			t.Errorf("stdout %q does not contain %q", stdout.String(), expected)
		}
	}
}

func TestAuditExcludesGeneratedTestsAndUnexportedReceivers(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "doc.go", `// Package sample is documented.
package sample
`)
	writeSource(t, root, "generated.go", `// Code generated by test. DO NOT EDIT.
package sample

type Generated struct{}
`)
	writeSource(t, root, "sample_test.go", `package sample

func ExportedTestHelper() {}
`)
	writeSource(t, root, "internal.go", `package sample

type internal struct{}

func (internal) ExportedMethod() {}

type internalInterface interface {
	ExportedMethod()
}
`)
	findings, err := audit([]string{root})
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 0 {
		t.Fatalf("findings = %#v", findings)
	}
}

