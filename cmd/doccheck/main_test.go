func TestAuditReportsPackageComment(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "sample.go", `package sample

// Value is documented.
const Value = 1
`)
	findings, err := audit([]string{root})
	if err != nil {
		t.Fatal(err)
	}
	if len(findings) != 1 || findings[0].symbol != "package sample" {
		t.Fatalf("findings = %#v", findings)
	}
}

func TestRunUsageAndParseErrors(t *testing.T) {
	var stdout, stderr bytes.Buffer
	if code := run(nil, &stdout, &stderr); code != 2 {
		t.Fatalf("run(nil) = %d, want 2", code)
	}
	if !strings.Contains(stderr.String(), "usage:") {
		t.Fatalf("stderr = %q", stderr.String())
	}

	root := t.TempDir()
	writeSource(t, root, "bad.go", "package")
	stdout.Reset()
	stderr.Reset()
	if code := run([]string{root}, &stdout, &stderr); code != 2 {
		t.Fatalf("run(parse error) = %d, want 2", code)
	}
	if !strings.Contains(stderr.String(), "doccheck:") {
		t.Fatalf("stderr = %q", stderr.String())
	}
}

func writeSource(t *testing.T, root, name, source string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(root, name), []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
}
